type TranslationKey = string;

type I18nContextValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: TranslationKey, fallback?: string) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

function getInitialLanguage(): Language {
  if (typeof window === 'undefined') return 'sq';
  const stored = window.localStorage.getItem(STORAGE_KEY);
  return stored === 'en' || stored === 'sq' || stored === 'de' ? stored : 'sq';
}

function resolveKey(language: Language, key: TranslationKey): string | null {
  const value = key.split('.').reduce<unknown>((acc, part) => {
    if (!acc || typeof acc !== 'object') return null;
    return (acc as Record<string, unknown>)[part] ?? null;
  }, translations[language]);

  return typeof value === 'string' ? value : null;
}

export function resolveTranslation(language: Language, key: TranslationKey): string | null {
  return resolveKey(language, key);
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(getInitialLanguage);

  useEffect(() => {
    window.localStorage.setItem(STORAGE_KEY, language);
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo<I18nContextValue>(() => ({
    language,
    setLanguage,
    t: (key, fallback) => resolveKey(language, key) ?? fallback ?? key,
  }), [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) throw new Error('useI18n must be used inside LanguageProvider.');
  return context;
}
